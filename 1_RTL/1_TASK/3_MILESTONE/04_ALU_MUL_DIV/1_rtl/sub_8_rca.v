`timescale 1ns/1ps

module sub_8_rca (
	i_a	,
	i_b	,
	i_bin	,
	o_diff	,
	o_bout
);


input	[7:0]	i_a	;
input	[7:0]	i_b	;
input		i_bin	;

output	[7:0] 	o_diff	;
output		o_bout	;

wire	[7:0] 	p	;
wire	[7:0]	g	;
wire	[8:0]	borrow	;


assign p = i_a ^ i_b	;
assign g = (~i_a) & i_b	;


assign borrow[0] = i_bin;

assign borrow[1] = g[0] |
		  ((~p[0]) & borrow[0]);

assign borrow[2] = g[1] |
		  ((~p[1]) & g[0]) |
		  ((~p[1]) & (~p[0]) & borrow[0]);

assign borrow[3] = g[2] |
		  ((~p[2]) & g[1]) |
		  ((~p[2]) & (~p[1]) & g[0]) |
		  ((~p[2]) & (~p[1]) & (~p[0]) & borrow[0]);

assign borrow[4] = g[3] |
		  ((~p[3]) & g[2]) |
		  ((~p[3]) & (~p[2]) & g[1]) |
		  ((~p[3]) & (~p[2]) & (~p[1]) & g[0]) |
		  ((~p[3]) & (~p[2]) & (~p[1]) & (~p[0]) & borrow[0]);

assign borrow[5] = g[4] |
		  ((~p[4]) & g[3]) |
		  ((~p[4]) & (~p[3]) & g[2]) |
		  ((~p[4]) & (~p[3]) & (~p[2]) & g[1]) |
		  ((~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & g[0]) |
		  ((~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & (~p[0]) & borrow[0]);

assign borrow[6] = g[5] |
		  ((~p[5]) & g[4]) |
		  ((~p[5]) & (~p[4]) & g[3]) |
		  ((~p[5]) & (~p[4]) & (~p[3]) & g[2]) |
		  ((~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & g[1]) |
		  ((~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & g[0]) |
		  ((~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & (~p[0]) & borrow[0]);

assign borrow[7] = g[6] |
		  ((~p[6]) & g[5]) |
		  ((~p[6]) & (~p[5]) & g[4]) |
		  ((~p[6]) & (~p[5]) & (~p[4]) & g[3]) |
		  ((~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & g[2]) |
		  ((~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & g[1]) |
		  ((~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & g[0]) |
		  ((~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & (~p[0]) & borrow[0]);

assign borrow[8] = g[7] |
		  ((~p[7]) & g[6]) |
		  ((~p[7]) & (~p[6]) & g[5]) |
	 	  ((~p[7]) & (~p[6]) & (~p[5]) & g[4]) |
		  ((~p[7]) & (~p[6]) & (~p[5]) & (~p[4]) & g[3]) |
		  ((~p[7]) & (~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & g[2]) |
		  ((~p[7]) & (~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & g[1]) |
		  ((~p[7]) & (~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & g[0]) |
		  ((~p[7]) & (~p[6]) & (~p[5]) & (~p[4]) & (~p[3]) & (~p[2]) & (~p[1]) & (~p[0]) & borrow[0]);


assign o_diff = p ^ borrow[7:0];
assign o_bout = borrow[8];

endmodule
